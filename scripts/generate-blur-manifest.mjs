#!/usr/bin/env node
/**
 * Blur-placeholder manifest generator.
 *
 * What it does:
 *   - Scans public/images/ for JPEG/PNG/WebP/AVIF files
 *   - Generates a tiny ~200-400 byte base64 data URL per image
 *     (10px wide, q=50 JPEG — Next.js auto-blurs at 40px viewport
 *     when used with `placeholder="blur" blurDataURL={...}`)
 *   - Writes src/lib/blur-manifest.ts with Record<string, string>
 *
 * Why:
 *   Next.js Image's `placeholder="blur"` only auto-generates blur data
 *   for STATIC IMPORTS. For images referenced by string path
 *   (`<Image src="/images/foo.jpg" />`), we must provide blurDataURL
 *   explicitly. This script generates them at build time so every
 *   string-path Image can render an instant blurred LQIP <200ms while
 *   the real image fetches — improving perceived LCP without changing
 *   actual LCP measurement.
 *
 * Bundle impact:
 *   Each blur entry is ~300-400 bytes. Tree-shaking ensures only
 *   blur entries actually used by a route get bundled into that route.
 *   Per-route cost: ~300 bytes (1 image) to ~2KB (5-6 images).
 *
 * Run: `node scripts/generate-blur-manifest.mjs`
 *      (or as part of prebuild — see package.json)
 *
 * Safe to re-run: deterministic output for same input.
 */

import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
import { join, extname } from "node:path";

const SCAN_ROOT = "public/images";
const OUTPUT_FILE = "src/lib/blur-manifest.ts";
const BLUR_WIDTH = 10; // 10px wide, height auto. Final dataURL ~300-400 bytes.
const JPEG_QUALITY = 50;

const EXTS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

async function* walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = join(dir, e.name);
    if (e.isDirectory()) yield* walk(full);
    else yield full;
  }
}

async function main() {
  const manifest = {};
  let count = 0;
  let totalBytes = 0;
  let largest = 0;

  for await (const file of walk(SCAN_ROOT)) {
    const ext = extname(file).toLowerCase();
    if (!EXTS.has(ext)) continue;

    try {
      const buf = await sharp(file)
        .resize(BLUR_WIDTH, null, { fit: "inside" })
        .jpeg({ quality: JPEG_QUALITY, mozjpeg: true })
        .toBuffer();
      // Public path — strip the "public" prefix so the key matches
      // what's used in <Image src="/images/..." />
      const publicPath = "/" + file.replace(/^public\//, "");
      manifest[publicPath] = "data:image/jpeg;base64," + buf.toString("base64");
      count++;
      totalBytes += buf.length;
      if (buf.length > largest) largest = buf.length;
    } catch (e) {
      console.warn(`  skip: ${file} (${e.message})`);
    }
  }

  // Sort keys alphabetically for deterministic diff
  const sortedKeys = Object.keys(manifest).sort();
  const sorted = Object.fromEntries(sortedKeys.map((k) => [k, manifest[k]]));

  const ts = `// AUTO-GENERATED by scripts/generate-blur-manifest.mjs.
// Do NOT edit by hand. Run \`node scripts/generate-blur-manifest.mjs\` to regenerate.
//
// Maps each public image path to a tiny base64-encoded blur placeholder
// (~300-400 bytes per entry). Used as \`blurDataURL\` on <Image placeholder="blur" />
// for instant LQIP rendering while the real image loads.
//
// Generated: ${new Date().toISOString()}
// Total entries: ${count}
// Total size: ${(totalBytes / 1024).toFixed(1)} KB
// Largest entry: ${largest} bytes

export const BLUR_MANIFEST: Record<string, string> = ${JSON.stringify(sorted, null, 2)};

/**
 * Generic dark-theme fallback blur (8×8 px, ~268 bytes). Matches site
 * dark-theme background (#0A0C12). Used when an image isn't in the
 * manifest yet — Next.js Image requires blurDataURL to be a string when
 * placeholder="blur", so getBlur() always returns a string.
 */
export const FALLBACK_BLUR =
  "data:image/jpeg;base64,/9j/2wBDABsSFBcUERsXFhceHBsgKEIrKCUlKFE6PTBCYFVlZF9VXVtqeJmBanGQc1tdhbWGkJ6jq62rZ4C8ybqmx5moq6T/2wBDARweHigjKE4rK06kbl1upKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKSkpKT/wAARCAAIAAgDASIAAhEBAxEB/8QAFQABAQAAAAAAAAAAAAAAAAAAAAb/xAAUEAEAAAAAAAAAAAAAAAAAAAAA/8QAFQEBAQAAAAAAAAAAAAAAAAAAAAH/xAAUEQEAAAAAAAAAAAAAAAAAAAAA/9oADAMBAAIRAxEAPwCdAUf/2Q==";

/** Get blur placeholder for an image path. Falls back to dark generic blur. */
export function getBlur(src: string): string {
  return BLUR_MANIFEST[src] || FALLBACK_BLUR;
}
`;

  await writeFile(OUTPUT_FILE, ts);
  console.log(
    `✓ Generated ${OUTPUT_FILE}: ${count} entries, ${(totalBytes / 1024).toFixed(1)} KB total (largest ${largest}B)`,
  );
}

main().catch((e) => {
  console.error("FAILED:", e);
  process.exit(1);
});
