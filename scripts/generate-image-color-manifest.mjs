#!/usr/bin/env node
/**
 * Image dominant-color manifest generator.
 *
 * What it does:
 *   - Scans public/images/ for JPEG/PNG/WebP/AVIF files
 *   - Resizes each to 1×1 pixel, reads RGB
 *   - Emits src/lib/image-color-manifest.ts with Record<string, string>
 *     (each value is a #rrggbb hex color)
 *
 * Why:
 *   Replaces the ill-fated `placeholder="blur"` experiment from
 *   2026-05-07 (see docs/PERF-EXPERIMENTS-2026-05-07.md).
 *
 *   That experiment used JPEG blurDataURL → Next.js converted it to
 *   inline SVG with feGaussianBlur → on Lighthouse mobile (4× CPU
 *   slowdown), the SVG paint cost regressed LCP by 6-9 seconds.
 *
 *   Flat color CSS background = zero paint cost (browser fills a rect
 *   with a single color). Renders before image fetches. Less informative
 *   than blur but still better than pitch black + does not regress on
 *   throttled mobile.
 *
 * How it's used:
 *   <div style={{backgroundColor: getColor("/images/studio/foo.jpg")}}>
 *     <Image src="/images/studio/foo.jpg" ... />
 *   </div>
 *
 * Bundle impact:
 *   Each entry is ~40 bytes (path + 7-char hex). Tree-shaking ensures
 *   only entries actually used by a route get bundled. Manifest size
 *   for 89 entries: ~4 KB total in src/lib/, near-zero per-route cost.
 *
 * Run: `node scripts/generate-image-color-manifest.mjs`
 *      (also runs as part of prebuild — see package.json)
 *
 * Deterministic: same input → same output.
 */

import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
import { join, extname } from "node:path";

const SCAN_ROOT = "public/images";
const OUTPUT_FILE = "src/lib/image-color-manifest.ts";

const EXTS = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif"]);

async function* walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = join(dir, e.name);
    if (e.isDirectory()) yield* walk(full);
    else yield full;
  }
}

function toHex(r, g, b) {
  return (
    "#" +
    [r, g, b]
      .map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, "0"))
      .join("")
  );
}

async function main() {
  const manifest = {};
  let count = 0;
  let skipped = 0;

  for await (const file of walk(SCAN_ROOT)) {
    const ext = extname(file).toLowerCase();
    if (!EXTS.has(ext)) continue;

    try {
      // Resize to 1×1 with default lanczos3 → average color
      const { data } = await sharp(file)
        .resize(1, 1, { fit: "inside" })
        .raw()
        .toBuffer({ resolveWithObject: true });
      const hex = toHex(data[0], data[1], data[2]);
      const publicPath = "/" + file.replace(/^public\//, "");
      manifest[publicPath] = hex;
      count++;
    } catch {
      skipped++;
    }
  }

  // Sort keys alphabetically for deterministic diff
  const sortedKeys = Object.keys(manifest).sort();
  const sorted = Object.fromEntries(sortedKeys.map((k) => [k, manifest[k]]));

  const ts = `// AUTO-GENERATED by scripts/generate-image-color-manifest.mjs.
// Do NOT edit by hand. Run \`node scripts/generate-image-color-manifest.mjs\`
// to regenerate (also runs in prebuild).
//
// Maps each public image path to its dominant (1×1 average) color as
// a #rrggbb hex string. Used as CSS \`background-color\` on the wrapper
// element behind <Image> so the user sees a meaningful color preview
// (matched to the image) before the actual image fetches.
//
// Why not blur placeholder: see docs/PERF-EXPERIMENTS-2026-05-07.md.
// (TL;DR: SVG feGaussianBlur regressed Lighthouse mobile LCP by 6-9s.)
//
// Generated: ${new Date().toISOString()}
// Total entries: ${count}
// Skipped (unsupported format): ${skipped}

export const IMAGE_COLOR_MANIFEST: Record<string, string> = ${JSON.stringify(sorted, null, 2)};

/** Fallback color for images not in the manifest. Matches site dark theme. */
export const FALLBACK_COLOR = "#0B0907";

/** Get dominant color for an image path. Falls back to dark theme color. */
export function getColor(src: string): string {
  return IMAGE_COLOR_MANIFEST[src] ?? FALLBACK_COLOR;
}
`;

  await writeFile(OUTPUT_FILE, ts);
  console.log(
    `✓ Generated ${OUTPUT_FILE}: ${count} entries${skipped ? `, ${skipped} skipped` : ""}`,
  );
}

main().catch((e) => {
  console.error("FAILED:", e);
  process.exit(1);
});
